#!/usr/bin/env python3
"""Generate src/gfx/font_data.c from Press Start 2P.

Usage: python3 -I tools/font/mkfont.py FONT.ttf OUT.c
Example: python3 -I tools/font/mkfont.py assets/fonts/PressStart2P-Regular.ttf src/gfx/font_data.c
"""
import sys
from PIL import Image, ImageDraw, ImageFont

BASE_X, BASE_Y, SIZE = 8, 20, 48


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    font = ImageFont.truetype(sys.argv[1], 8)
    glyphs = []
    for code in range(0x20, 0x7F):
        img = Image.new("1", (SIZE, SIZE), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((BASE_X, BASE_Y), chr(code), font=font, fill=1, anchor="ls")
        glyphs.append((code, img, img.getbbox()))
    boxes = [b for _, _, b in glyphs if b]
    x0 = min(b[0] for b in boxes)
    y0 = min(b[1] for b in boxes)
    rows = []
    for code, img, bb in glyphs:
        if bb and (bb[2] - x0 > 8 or bb[3] - y0 > 8):
            sys.exit("glyph %r does not fit 8x8: box %r origin (%d,%d)" % (chr(code), bb, x0, y0))
        px = img.load()
        r = []
        for j in range(8):
            v = 0
            for i in range(8):
                if px[x0 + i, y0 + j]:
                    v |= 0x80 >> i
            r.append(v)
        rows.append((code, r))
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by tools/font/mkfont.py from Press Start 2P "
                "(SIL OFL 1.1, see assets/fonts/OFL.txt). Do not edit. */\n")
        f.write('#include "gfx/font.h"\n\n')
        f.write("const uint8_t FONT8[95][8] = {\n")
        for code, r in rows:
            f.write("\t{%s},\t/* %s */\n" % (", ".join("0x%02x" % b for b in r),
                                              "0x%02x %s" % (code, chr(code) if code != 0x2A and code != 0x2F else "x")))
        f.write("};\n")


main()
